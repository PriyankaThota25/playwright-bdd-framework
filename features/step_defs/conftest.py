from __future__ import annotations

import uuid

import pytest
from playwright.sync_api import Page
from pytest_bdd import given, then, when

from pages.account_information_page import AccountInformationPage
from pages.confirmation_page import ConfirmationPage
from pages.home_page import HomePage
from pages.login_page import LoginPage
from pages.signup_page import SignupPage

# Fixtures and steps here are visible to every step-def file under
# features/step_defs/, since conftest.py fixtures cascade to the whole
# directory tree. Put steps shared across multiple feature files here;
# keep steps specific to one feature in that feature's own
# test_<feature>_steps.py.


@pytest.fixture
def login_page(page: Page) -> LoginPage:
    return LoginPage(page)


@pytest.fixture
def home_page(page: Page) -> HomePage:
    return HomePage(page)


@given("I am on the login page")
def navigate_to_login_page(login_page: LoginPage) -> None:
    login_page.open()


@given("I am on the home page")
def navigate_to_home_page(home_page: HomePage) -> None:
    home_page.open()


@pytest.fixture
def signup_page(page: Page) -> SignupPage:
    return SignupPage(page)


@pytest.fixture
def account_information_page(page: Page) -> AccountInformationPage:
    return AccountInformationPage(page)


@pytest.fixture
def new_customer() -> dict:
    """Shared storage for the customer generated by the signup step, read
    back by later steps in the same scenario."""
    return {}


@when("I sign up as a new customer")
def sign_up_as_new_customer(
    signup_page: SignupPage,
    account_information_page: AccountInformationPage,
    page: Page,
    new_customer: dict,
) -> None:
    unique_id = uuid.uuid4().hex[:10]
    new_customer["name"] = f"QA Tester {unique_id}"
    new_customer["email"] = f"qa.tester.{unique_id}@example.com"

    signup_page.open()
    signup_page.start_signup(new_customer["name"], new_customer["email"])

    account_information_page.fill_account_details(
        password="Test@12345",
        first_name="QA",
        last_name=f"Tester{unique_id}",
        address="123 Test Street",
        country="United States",
        state="California",
        city="Los Angeles",
        zipcode="90001",
        mobile_number="9876543210",
    )

    ConfirmationPage(page, "account-created").continue_to_home()


@then("I should be logged in as the new customer")
def assert_logged_in_as_new_customer(home_page: HomePage, new_customer: dict) -> None:
    home_page.wait_until_logged_in()
    assert home_page.username() == new_customer["name"]
